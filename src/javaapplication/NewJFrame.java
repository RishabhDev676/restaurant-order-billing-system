    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   
    try {
        String qtyText = txtQuantity.getText().trim();
        if (qtyText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(null, "Please enter valid quantity.");
            return;
        }

        int qty = Integer.parseInt(qtyText);
        if (qty <= 0) {
            javax.swing.JOptionPane.showMessageDialog(null, "Quantity must be greater than 0.");
            return;
        }

        String selectedItemStr = (String) cmbItems.getSelectedItem();
        String[] parts = selectedItemStr.split(" - ₹");
        String itemName = parts[0];
        double price = Double.parseDouble(parts[1]);

        double amount = qty * price;
        grandTotal += amount;

        orderSummary.append(qty)
                    .append(" x ")
                    .append(itemName)
                    .append(" - ₹")
                    .append((int) price)
                    .append(" = ₹")
                    .append(amount)
                    .append("\n");

        txtReceipt.setText(orderSummary.toString());
        txtQuantity.setText("");

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(null, "Please enter valid quantity.");
    }



        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

