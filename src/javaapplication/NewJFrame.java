    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    if (grandTotal == 0) {
        javax.swing.JOptionPane.showMessageDialog(null, "No items ordered yet!");
        return;
    }

    // Format current date & time (dd/MM/yyyy HH:mm:ss)
    java.text.SimpleDateFormat formatter = new java.text.SimpleDateFormat("dd/MM/yyyy HH:mm:ss");
    String currentDateTime = formatter.format(new java.util.Date());

    // Build the final receipt display
    StringBuilder bill = new StringBuilder(orderSummary.toString());
    bill.append("-----------------------------\n");
    bill.append("Total Amount: ₹").append(grandTotal).append("\n");
    bill.append("Date & Time: ").append(currentDateTime).append("\n");
    bill.append("-----------------------------\n");
    bill.append("   Thank You! Visit Again!   ");

    // Output to the Receipt text area
    txtReceipt.setText(bill.toString());
   
       
    }//GEN-LAST:event_jButton2ActionPerformed

    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
    // Check if there's anything to print first
    if (txtReceipt.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "There is no receipt to print!");
        return;
    }

    try {
        // Send the text area directly to the system printer
        boolean complete = txtReceipt.print(
            new java.text.MessageFormat("Foodie's Paradise - Receipt"), // Header text
            new java.text.MessageFormat("Page {0}"),                   // Footer text
            true,                                                     // Show interactive print dialog
            null,                                                     // Printer attributes
            null,                                                     // Print request attributes
            true                                                      // Interactive mode
        );

        if (complete) {
            javax.swing.JOptionPane.showMessageDialog(this, "Receipt printed successfully!");
        }
    } catch (java.awt.print.PrinterException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Printing failed: " + e.getMessage());
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnPrintActionPerformed

